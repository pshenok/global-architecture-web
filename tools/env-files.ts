/**
 * Writes .env.local (mode 0600) when it is missing: the local stack's URLs, the client
 * registration read from the monolith's modules.json (devIdp.clients) and a fresh random
 * session key. No key material is ever committed, not even for development.
 */
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, readMonolithRegistry, readRegistry } from './lib.ts';

export const ENV_FILE = join(ROOT, '.env.local');

export function ensureEnvFile(): boolean {
  if (existsSync(ENV_FILE)) return false;
  const { app } = readRegistry();
  const monolith = readMonolithRegistry();
  const client = monolith.devIdp.clients?.find((c) => c.clientId === app.clientId);
  if (!client) {
    throw new Error(
      `the monolith's modules.json registers no dev IdP client "${app.clientId}" (devIdp.clients); update the monolith checkout`,
    );
  }
  const key = randomBytes(32).toString('base64url');
  const lines = [
    '# Local development values, generated by tools/env-files.ts (git-ignored).',
    `APP_ORIGIN=http://localhost:${app.devPort}`,
    `API_BASE_URL=https://localhost:${monolith.api.httpsPort}`,
    `OIDC_ISSUER=http://127.0.0.1:${monolith.devIdp.port}`,
    `OIDC_CLIENT_ID=${client.clientId}`,
    `OIDC_CLIENT_SECRET=${client.clientSecret}`,
    `SESSION_KEYS=[{"kid":"local-1","key":"${key}"}]`,
    'LOG_LEVEL=info',
    '',
  ];
  writeFileSync(ENV_FILE, lines.join('\n'), { mode: 0o600 });
  return true;
}

if (import.meta.main && ensureEnvFile()) console.log(`env-files: wrote ${ENV_FILE}`);
